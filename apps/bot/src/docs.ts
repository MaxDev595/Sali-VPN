export function docBySlug(slug: string) {
  return DOC_TOPICS.find((topic) => topic.slug === slug);
}

export function helpUrl(siteUrl: string, slug?: string) {
  return slug ? `${siteUrl}/help/${slug}` : `${siteUrl}/help`;
}
